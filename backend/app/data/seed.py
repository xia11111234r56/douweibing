def _insert_diseases(db) -> dict[str, Disease]:
    host = Host(
        name="绿豆",
        scientific_name="Vigna radiata (L.) Wilczek",
        description="一年生豆科作物，北方春播夏收，南方可春/夏/秋播，喜温暖湿润。",
    )
    db.add(host)

    symptom_map: dict[str, Symptom] = {}
    diseases: dict[str, Disease] = {}

    for item in DISEASES:
        name = item["name"]
        d = Disease(
            name=name,
            disease_type=DISEASE_TYPES[name],
            pathogen=item["pathogen"],
            symptoms=item["symptoms"],
            conditions=item["conditions"],
            host=host,
        )
        db.add(d)
        db.flush()
        diseases[name] = d

        for sname in item["symptom_names"]:
            if sname not in symptom_map:
                sym = Symptom(name=sname)
                db.add(sym)
                db.flush()
                symptom_map[sname] = sym
            db.execute(
                disease_symptom.insert().values(
                    disease_id=d.id, symptom_id=symptom_map[sname].id
                )
            )
    return diseases


def _insert_treatments(db, diseases: dict[str, Disease]) -> None:
    for dname, levels in TREATMENTS.items():
        disease = diseases[dname]
        for severity, methods in levels.items():
            for method_type, content in methods:
                db.add(
                    Treatment(
                        disease_id=disease.id,
                        severity_level=severity,
                        method_type=method_type,
                        content=content,
                    )
                )


def _insert_pesticides(db) -> list[Pesticide]:
    out = []
    for name, ingredient, usage in PESTICIDES:
        p = Pesticide(name=name, active_ingredient=ingredient, usage=usage)
        db.add(p)
        db.flush()
        out.append(p)
    return out


def _insert_env_rules(db, diseases: dict[str, Disease]) -> None:
    for condition, dname, adjustment in ENV_RULES:
        db.add(
            DiseaseEnvRule(
                disease_id=diseases[dname].id,
                condition=condition,
                adjustment=adjustment,
            )
        )


def _insert_graph(db, diseases: dict[str, Disease], pesticides: list[Pesticide]) -> None:
    """灌入图谱节点与边（双后端图引擎抽象层的 SQL 事实源）。

    读/算：SQL 后端用内存 networkx；Neo4j 后端读此表只读只算 + 尽力镜像
    （services/graph_backend_neo4j.py），漂移由 data/sync_neo4j.py 全量重建自愈。
    """
    nodes: dict[str, GraphNode] = {}

    def get_node(label: str, name: str) -> GraphNode:
        key = f"{label}:{name}"
        if key not in nodes:
            node = GraphNode(label=label, name=name)
            db.add(node)
            db.flush()
            nodes[key] = node
        return nodes[key]

    host_node = get_node("寄主", "绿豆")
    for dname, d in diseases.items():
        d_node = get_node("病害", dname)
        db.add(GraphEdge(source_id=host_node.id, target_id=d_node.id, relation="感染"))
        for sym in d.symptoms.split("，")[:3]:
            if len(sym) > 1:
                s_node = get_node("症状", sym)
                db.add(GraphEdge(source_id=d_node.id, target_id=s_node.id, relation="表现为"))

    for p in pesticides:
        p_node = get_node("药剂", p.name)
        for d in diseases.values():
            if any(p.name in content for _, content in TREATMENTS.get(d.name, {}).get("中度", [])):
                db.add(GraphEdge(source_id=d.id, target_id=p_node.id, relation="防治"))

    for condition, dname, _ in ENV_RULES:
        env_node = get_node("环境", condition)
        db.add(GraphEdge(source_id=diseases[dname].id, target_id=env_node.id, relation="适宜"))


